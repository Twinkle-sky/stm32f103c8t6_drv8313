/* 三角函数实现 */
/**
  * @brief  正弦函数近似计算（查表法）
  * @param  a: 角度值 (0-6283, 对应0-2π)
  * @retval 正弦值 * 1000 (-1000到1000)
  */
int32_t _sin_q10(uint16_t a)
{
    // 将角度映射到0-π/2范围进行查表
    if(a < _PI_2_1000) {
        // 第一象限：直接查表
        return sine_array[a];      // index检查[0,1570）
    }
    else if(a < _PI_1000) {
        // 第二象限：sin(a) = sin(π - a)
        return sine_array[3141 - a];     // index检查[3141-3141,3141-1570）
    }
    else if(a < _3PI_2_1000) {
        // 第三象限：sin(a) = -sin(a - π)
        return -sine_array[a - 3141];    // index检查[3141-3141,4712-3141）
    } 
    else {
        // 第四象限：sin(a) = -sin(2π - a)
        return -sine_array[6283 - a];    // index检查[6283-6283,6283-4712]  
    }
}

/**
  * @brief  余弦函数近似计算
  * @param  a: 角度值 (0-6283, 对应0-2π)
  * @retval 余弦值 * 1000 (-1000到1000)
  */
int32_t _cos_q10(uint16_t a)
{
    // cos(a) = sin(a + π/2)
    volatile uint16_t a_sin = a + _PI_2_1000;
    // 角度归一化到0-2π范围
    a_sin = a_sin > _2PI_1000 ? a_sin - _2PI_1000 : a_sin;
    return _sin_q10(a_sin);
}

/**
  * @brief  快速atan2近似计算
  * @param  y: y坐标 (Q10格式)
  * @param  x: x坐标 (Q10格式)
  * @retval 角度 (0-6283，对应0-2π)
  */
int32_t fast_atan2_int(int32_t y, int32_t x)
{
    int32_t angle = 0;
    
    /* 处理特殊情况 */
    if (x == 0) {
        return (y >= 0) ? 1571 : 4712;  /* π/2 或 3π/2 */
    }
    
    /* 计算|y/x|的绝对值 (Q10格式) */
    int32_t ratio = (y << 10) / (x);
		if(ratio<0)ratio=-ratio;
		
    
    /* 使用分2段线性近似或多项式近似 */
    
    /* 方法1：改进的分3段线性近似 */
    if (ratio < 512) {  /* 0.5 */
        angle = ratio;//0~512
    } else if(ratio<1024){
        angle=512 + ((ratio-512)>>1);//512~768
    }
		else {
        angle=768 + ((ratio-1024)>>2);//768~
    }
		
    if(angle>_PI_2_1000)angle=_PI_2_1000;
    
    /* 调整符号和象限 */
    if (x > 0) {
        if (y >= 0) {
            /* 第一象限 */
            return angle;
        } else {
            /* 第四象限 */
            return 6283 - angle;  /* 2π - angle */
        }
    } else {
        if (y >= 0) {
            /* 第二象限 */
            return 3141 - angle;  /* π - angle */
        } else {
            /* 第三象限 */
            return 3141 + angle;  /* π + angle */
        }
    }
}

/**
  * @brief  角度标准化
  * @param  angle: 输入角度
  * @retval 标准化后的角度 (0-6283)
  */
uint16_t FOC_AngleNormalize(uint16_t angle)
{
    /* 如果角度在0-2π范围内，直接返回 */
    if(angle < _2PI_1000) {
        return angle;
    }
    
    /* 使用减法循环，避免取模运算 */
    while(angle >= _2PI_1000) {
        angle -= _2PI_1000;
    }
    
    return angle;
}
/**
  * @brief  角度归一化到0-2π范围
  * @param  angle: 输入角度
  * @retval 归一化后的角度 (0-6283)
  */
uint16_t _normalizeAngle(int32_t angle)
{
    // 取模运算，确保角度在0-2π范围内
    volatile int32_t a = angle % _2PI_1000;
    // 处理负数情况
    if(a < 0) a += _2PI_1000;
    return (uint16_t)a;
}

/**
  * @brief  Q10格式乘法
  * @param  a: 被乘数 (Q10格式)
  * @param  b: 乘数 (Q10格式)
  * @retval 乘积 (Q10格式)
  */
int32_t FOC_MulQ10(int32_t a, int32_t b)
{
    /* 两个Q10数相乘，结果需要右移10位以保持Q10格式 */
    volatile int64_t result = (int64_t)a * b;
    return (int32_t)(result >> 10);
}

/**
  * @brief  快速整数平方根计算
  * @param  x: 输入值
  * @retval 平方根
  */
int32_t _sqrt_fast(int32_t x)
{
    if(x <= 0) return 0;
    
    int32_t guess = 0;
    int32_t bit = 1 << 15;  /* 从最高位开始 */
    
    while(bit > 0) {
        guess |= bit;
        if(guess * guess > x) {
            guess ^= bit;
        }
        bit >>= 1;
    }
    
    return guess;
}